"""7.1 — 입력 2개 → 은닉 뉴런 3개 → 출력 1개의 순전파 계산.

NumPy와 고정된 가중치로 계산만 확인하는 예제입니다. 모델 학습은 수행하지 않습니다.
"""
import numpy as np

# 1. 입력값 두 개 (임의의 예시 값이며 실제 관측값이 아님)
x = np.array([0.6, 0.8])

# 2. 첫 번째 연결: 입력 2개 → 은닉 뉴런 3개
# W1: (2, 3) 형태의 가중치, b1: 은닉 뉴런마다 더할 편향 3개
# 두 번째 뉴런의 가중치를 음수로 설정해 ReLU의 변화를 확인합니다.
W1 = np.array([[0.4, -0.9, 0.7],
               [0.2,  0.6, -0.1]])
b1 = np.array([0.1, 0.0, 0.2])

# 3. 두 번째 연결: 은닉 뉴런 3개 → 최종 출력 1개
W2 = np.array([[0.5], [-0.4], [0.8]])
b2 = np.array([0.1])

# 4. 순전파: 가중합 → ReLU → 최종 출력
z = x @ W1 + b1            # @: 입력과 가중치의 행렬 곱셈
hidden = np.maximum(z, 0)   # ReLU: 음수는 0, 0 이상은 그대로
output = hidden @ W2 + b2  # 출력층에서는 ReLU를 사용하지 않음

print("입력:", x)
print("은닉층 가중합:", np.round(z, 3))
print("은닉층 ReLU 출력:", np.round(hidden, 3))
print("최종 출력:", np.round(output, 3))
print("참고: 고정된 가중치로 계산만 하며 학습하는 모델은 아닙니다.")
